/**
 * 経路に含まれる乗り物の種類を、区間の一覧から集めます。
 *
 * @param {Array<{line?:string}>} legs
 * @returns {string[]} 種類（重複なし、出てきた順）
 */
export function kindsOf(legs) {
  const out = [];
  for (const leg of legs ?? []) {
    const { kind } = classifyLine(leg?.line);
    if (kind !== "walk" && !out.includes(kind)) out.push(kind);
  }
  return out;
}

/**
 * その経路が、指定された乗り物に合っているか。
 *
 * 優先する種類が無い（おまかせ・電車）なら、どれでも合っています。
 */
export function matchesPreference(legs, transport) {
  const want = preferredKinds(transport);
  if (!want.length) return true;
  const have = kindsOf(legs);
  return want.some((k) => have.includes(k));
}

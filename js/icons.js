/** その名前の形があるか。 */
export function hasIcon(name) {
  const key = ALIAS[name] ?? name;
  return Object.hasOwn(PATHS, key);
}

/**
 * その名前の線（path の d）。
 *
 * DOM の要らないところから使います。index.html には**同じ形**を
 * 直接書いてあるので（画面が出るより先に見える記号は、JS を待たせ
 * たくありません）、ずれていないかを試験でここと突き合わせます。
 *
 * @returns {string} 名前が無ければ空
 */
export function iconPath(name) {
  const key = ALIAS[name] ?? name;
  return PATHS[key] ?? "";
}

/** ぜんぶの名前（別名は含みません）。 */
export function iconNames() {
  return Object.keys(PATHS);
}

/** 線の太さ。どの記号でも同じにします。 */
export const STROKE_WIDTH = "1.6";

/**
 * 記号を1つ作ります。
 *
 * @param {string} name PATHS の名前（無ければ dot）
 * @param {{class?:string, title?:string}} [opts]
 *   title を渡したときだけ、読み上げに出ます。ふつうは渡しません
 *   （字が横に書いてあるので、読むと二度になります）。
 * @returns {SVGElement}
 */
export function icon(name, opts = {}) {
  const key = ALIAS[name] ?? name;
  const d = PATHS[key] ?? PATHS.dot;
  const NS = "http://www.w3.org/2000/svg";
  const svg = document.createElementNS(NS, "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("fill", "none");
  svg.setAttribute("stroke", "currentColor");
  // 線の太さは、どの記号でも同じです。ここがそろっていないと、
  // 並べたときに太さの違いだけが目に付きます。
  svg.setAttribute("stroke-width", STROKE_WIDTH);
  svg.setAttribute("stroke-linecap", "round");
  svg.setAttribute("stroke-linejoin", "round");
  svg.setAttribute("class", `ic${opts.class ? ` ${opts.class}` : ""}`);
  // どの記号かを、画面からも読めるようにします。読み上げには出ません
  // （aria-hidden のままです）。絵文字のころは textContent を見れば
  // 分かりましたが、SVG は中身が線なので、名前を持たせておかないと
  // 試験も不具合調べもできません。
  svg.setAttribute("data-icon", key);
  if (opts.title) {
    svg.setAttribute("role", "img");
    const t = document.createElementNS(NS, "title");
    t.textContent = opts.title;
    svg.append(t);
  } else {
    // **読み上げません。** 字は横に書いてあります。
    svg.setAttribute("aria-hidden", "true");
    svg.setAttribute("focusable", "false");
  }
  const path = document.createElementNS(NS, "path");
  path.setAttribute("d", d);
  svg.append(path);
  return svg;
}


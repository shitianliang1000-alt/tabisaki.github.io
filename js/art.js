// カードの「絵」。写真の代わりに置くものです。
//
// 写真を優先したいのですが、収録データに写真はありません。写真のない
// カードは文字の塊になり、10件並べると見分けがつきません。そこで、
// 場所ごとに決まった絵を作ります。
//
// 決まった、というのが肝です。開くたびに色が変われば、同じカードが
// 別の場所に見えます。名前から数を作り、そこから色を決めます。
// 乱数は使いません。
//
// 分類ごとに色相の帯を決めてあるので、海は青緑、温泉は橙、山は緑に
// なります。写真ほどではありませんが、一覧を流し見たときに
// 「どんな場所か」がなんとなく伝わります。
//
// 実際の写真が取れる場合は photos.js がこの上に重ねます。
// 取れなければ、この絵のままです。

/** 文字列 → 0以上の整数。同じ文字列は必ず同じ数になります。 */
function hashOf(text) {
  let h = 2166136261;
  for (const ch of String(text ?? "")) {
    h ^= ch.codePointAt(0);
    h = Math.imul(h, 16777619) >>> 0;
  }
  return h >>> 0;
}


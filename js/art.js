/**
 * その場所の絵。
 *
 * @param {{id?:string, name?:string, category?:string}} spot
 * @returns {{css:string, hue:number, icon:string, ink:string}}
 *   css … background にそのまま入れられる文字列
 *   ink … その絵の上に載せる文字の色（明るい絵には濃い字）
 */
export function artFor(spot) {
  const key = `${spot?.id ?? ""}|${spot?.name ?? ""}|${spot?.category ?? ""}`;
  const h = hashOf(key || "旅さき");
  const band = HUE_BAND[spot?.category] ?? DEFAULT_BAND;
  const span = (band[1] - band[0] + 360) % 360;
  const hue = Math.round((band[0] + (h % (span + 1))) % 360);

  // 2色目は、色相環で少し離した位置に。近すぎると平坦になりますが、
  // 離しすぎると分類の色味から外れます（温泉のはずが黄緑になる）。
  // 10〜28度に収めます。
  const hue2 = (hue + 10 + ((h >> 8) % 18)) % 360;
  const angle = 100 + ((h >> 16) % 80);        // 100〜180度
  const light = 62 + ((h >> 4) % 12);          // 62〜73%
  const sat = 38 + ((h >> 12) % 22);           // 38〜59%

  // 3層。奥に色の面、手前にやわらかい光。写真の代わりなので、
  // 平らな2色よりも「奥行き」があるほうがカードとして持ちます。
  const css = [
    `radial-gradient(120% 90% at 22% 18%,`
      + ` hsl(${hue2} ${sat + 8}% ${light + 14}% / .85), transparent 62%)`,
    `radial-gradient(90% 80% at 82% 88%,`
      + ` hsl(${hue} ${sat}% ${light - 16}% / .7), transparent 58%)`,
    `linear-gradient(${angle}deg,`
      + ` hsl(${hue} ${sat}% ${light}%), hsl(${hue2} ${sat - 6}% ${light - 10}%))`,
  ].join(", ");

  return {
    css, hue,
    icon: ICON[spot?.category] ?? "📍",
    // 明るい面なので、上に載せる文字は温かみのある黒にします。
    ink: "#2a2420",
  };
}

/** 雰囲気チップ（「温泉でゆっくり」など）の絵。 */
export function moodArt(label) {
  return artFor({ id: "mood", name: label, category: moodCategory(label) });
}

/** 雰囲気の言葉から、いちばん近い分類を当てます。 */
function moodCategory(label) {
  const s = String(label ?? "");
  const table = [
    ["温泉", "温泉"], ["湯", "温泉"],
    ["自然", "自然"], ["森", "山"], ["山", "山"], ["登", "登山"],
    ["海", "海岸"], ["島", "海岸"], ["湖", "湖"],
    ["歴史", "史跡"], ["寺", "寺院"], ["神社", "神社"], ["城", "城"],
    ["美術", "美術館"], ["アート", "美術館"], ["博物", "博物館"],
    ["食", "グルメ"], ["グルメ", "グルメ"], ["市場", "市場"],
    ["絶景", "展望台"], ["景", "展望台"], ["写真", "展望台"],
    ["街", "町並み"], ["静か", "自然"], ["オーロラ", "展望台"],
  ];
  for (const [word, cat] of table) if (s.includes(word)) return cat;
  return "観光名所";
}

import { findTrains } from "./trains.js";
// 希望文から、乗り物と旅のしかたの指定を読み取る。
//
// 書かれていることの多くは「どこへ行きたいか」ですが、**どう行きたいか**
// を書く人もいます。
//
//     サンライズに乗って山陰へ
//     観光列車に乗りたい
//     ツーリングをしたい
//     レンタカーで回りたい
//
// これまでは、どれも素通りしていました。文の中の語はスポット名との
// 照合にしか使われないので、「ツーリング」に合うスポットが無ければ
// 無視されます。結果、バイクで回りたい人に「徒歩15分」の旅程が出ます。
//
// ここで読み取るのは2つだけです。
//
//   transport … 何で移動するか（画面の選択と同じ値）
//   notes     … 旅程に添える一言（何を読み取ったかを、読む人に見せる）
//
// **読み取れないものは、読み取れないままにします。** 「サンライズ」は
// 寝台特急の名前で、時刻表は引けますが席の有無までは分かりません。
// 分かるのは「夜行で移動したいらしい」ということだけです。そこまでを
// 伝えて、あとは本人に任せます。

/**
 * 乗り物の指定。長い言い回しから順に見ます（「レンタカー」を
 * 「カー」で拾わないように）。
 */
const VEHICLES = [
  // 空路＋現地の車。「飛行機で行ってレンタカー」はいちばん多い形です。
  // **空路だけの指定より先に見ます**（「飛行機で」で拾ってしまうと、
  // 現地も電車・バスで組むことになります）。
  { re: /(飛行機|空路|空港|航空機)[^。]{0,14}(レンタカー|カーシェア|車を借り)|(レンタカー|カーシェア)[^。]{0,14}(飛行機|空路|空港|航空機)/,
    transport: "air+car",
    note: "行きは空路、現地は車の道のりで組んでいます。空港では"
      + "搭乗手続きが要ります（手荷物を預けるなら出発の60分前に）" },
  // 空路。**車より先に見ます**（「空港までレンタカー」を車と読むより、
  // 空路の旅として組むほうが近いためです）。
  { re: /(飛行機|航空機|空路|LCC|ANA|JAL|ジェットスター|ピーチ|スカイマーク|by (plane|air)|flight)/i,
    transport: "air",
    note: "空路で組んでいます。空港では搭乗手続きが要るので、"
      + "手荷物を預けるなら出発の60分前に空港へ。"
      + "搭乗券は別に取ってください" },
  // 船。フェリーでしか行けない島があります。
  { re: /(フェリー|客船|カーフェリー|ジェットフォイル|高速船|船で|船旅|渡船|by (ferry|ship))/i,
    transport: "ferry",
    note: "船を使う経路を選んでいます。船は欠航することがあるので、"
      + "前日と当日の朝に運航状況を確かめてください" },
  { re: /ツーリング|バイク|オートバイ|motorcycle|touring/i,
    transport: "car",
    note: "バイクで回る前提で、道のりから所要時間を見ています"
      + "（電車・バスの時刻表は使いません）" },
  // 行きは電車、現地は車。**車の指定より先に見ます**。
  // 「新幹線で行ってレンタカー」を「レンタカー」で拾うと、出発地から
  // 目的地まで運転する旅程になります（600km を車で、という旅です）。
  { re: /(新幹線|特急|電車|列車|鉄道)[^。]{0,12}(レンタカー|カーシェア|駅レンタ)|(レンタカー|カーシェア)[^。]{0,12}(新幹線|特急|電車|列車)|現地[^。]{0,6}(レンタカー|カーシェア|車)|駅レンタカー/,
    transport: "transit+car",
    note: "遠出は電車・バスの便、現地は車の道のりで組んでいます" },
  // 「車で」は、**前の字を見ないと当たります**。「電車で回りたい」の
  // 中にも「車で」が入っているので、電車の指定を車と読んでいました。
  { re: /レンタカー|マイカー|自家用車|(?<![電列汽馬])車で|ドライブ|rent-?a-?car|by car|driving/i,
    transport: "car",
    note: "車で回る前提で、道のりから所要時間を見ています" },
  { re: /自転車|サイクリング|チャリ|cycling|bicycle/i,
    transport: "walk",
    note: "自転車で回る前提です。所要時間は徒歩に近い見かたをしています" },
  { re: /歩いて|散策|街歩き|walking|on foot/i,
    transport: "walk",
    note: "歩いて回れる範囲で組んでいます" },
  // 普通列車のみ。**新幹線と特急を切って調べます。**
  // これまでは "transit" と同じ扱いで、時刻表への問い合わせでは
  // 新幹線も特急も使われていました。18きっぷでは乗れない便で
  // 組まれた旅程は、そのまま使えません。
  { re: /青春18|18きっぷ|鈍行|各駅停車|普通列車のみ|普通列車だけ/,
    transport: "local",
    note: "普通列車と快速だけで組んでいます（新幹線と有料特急は"
      + "使いません）。実際の便は時刻表でご確認ください" },
  { re: /電車|列車|鉄道|バスで|公共交通|by train|railway/i,
    transport: "transit",
    note: "電車・バスで回る前提です" },
];

/**
 * 特定の列車・船。名前は分かっても、席が取れるかまでは分かりません。
 * 分かるところまでを伝えて、確かめかたを添えます。
 */
const NAMED_SERVICES = [
  // 名前のある列車は js/trains.js が拾います（ここでは重ねません）。
  { re: /観光列車|トロッコ列車|SL|蒸気機関車|ジョイフルトレイン/,
    note: "観光列車は運転日が限られ、座席の指定が要るものがほとんどです。"
      + "旅程では普通の移動として見ているので、乗りたい列車が決まって"
      + "いれば、その時刻に合わせて前後をずらしてください" },
  { re: /ムーンライト/,
    note: "ムーンライトながらなどの夜行快速は、いまは走っていません。"
      + "夜行で移動したい区間があれば、高速バスもご検討ください" },
  { re: /フェリー|客船|ferry/i,
    note: "フェリーは便数が少なく、時刻表も別系統です。"
      + "航路がある区間は、運航会社の時刻表でご確認ください" },
];

/**
 * 希望文から、乗り物と添える一言を読み取ります。
 *
 * @param {string} text
 * @returns {{transport: string|null, notes: string[], nightTrain: string|null,
 *            toward: string[]}}
 *   transport が null なら、指定は読み取れていません（画面の選択に従います）。
 *   nightTrain は狙っている夜行列車の id（"any" なら列車の指定なし）。
 */
export function readIntent(text) {
  const s = String(text ?? "");
  const notes = [];
  let transport = null;
  // 名前のある列車。時刻まで収録しているもの（サンライズ）と、
  // 走る区間だけのもの（サフィール踊り子など）に分かれます。
  const { timetabled, named } = findTrains(s);

  for (const v of VEHICLES) {
    if (!v.re.test(s)) continue;
    transport = v.transport;
    notes.push(v.note);
    break;                      // いちばん具体的な1つだけ
  }
  for (const n of NAMED_SERVICES) {
    if (n.re.test(s) && n.note) notes.push(n.note);
  }
  // 区間だけ収録している列車は、時刻を書きません。代わりに、どこへ
  // 向かう列車かを伝えて、確かめかたを添えます。
  for (const t of named) notes.push(t.note);
  // 名前のある列車が書かれていれば、電車で回る旅です。
  if (!transport && (timetabled || named.some((t) => t.bookable !== false))) {
    transport = "transit";
  }
  return {
    transport, notes,
    nightTrain: timetabled,
    // 行き先を寄せるための地名（「サフィール」なら伊豆）。
    toward: named.filter((t) => t.bookable !== false)
      .flatMap((t) => t.toward ?? []),
  };
}

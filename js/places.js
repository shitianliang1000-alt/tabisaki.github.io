/** 名前から場所を引きます。前後の空白と全角空白は無視します。 */
/** 収録の出発地はすべて日本国内です。国際線の判定に使います。 */
for (const p of PLACES) p.country = "日本";

export function findPlace(name) {
  const q = String(name ?? "").trim().replace(/[\s　]+/g, "");
  if (!q) return null;
  const exact = PLACES.find((p) => p.name === q);
  if (exact) return exact;
  // 「新宿」でも「新宿駅」に当たるようにする
  return PLACES.find((p) => p.name.replace(/駅$/, "") === q.replace(/駅$/, ""))
    ?? PLACES.find((p) => p.name.includes(q))
    ?? null;
}

/**
 * 緯度経度から、いちばん近い出発地の候補と、そこまでの距離を返します。
 *
 * 現在地をそのまま出発地にはしません。経路検索は駅を起点にするほうが
 * 実態に合いますし、「新宿駅から」のほうが利用者にも確かめようがあります。
 * 遠すぎるとき（収録の駅から200km以上）は null を返します。海の上や
 * 国外から開かれたときに、いちばんマシな駅を無言で選ばないためです。
 *
 * 距離も返すのは、**どれくらい近いのかで言うべきことが変わる**ためです。
 * 3km 先の駅なら「現在地からいちばん近い駅です」で通じますが、
 * 120km 先の駅を同じ言葉で入れると、現在地を取った意味がないどころか、
 * 勝手に遠くへ動かされたように見えます。距離を添えて断るか、
 * 添えて認めるかは、呼び出す側（js/app.js）で決めます。
 *
 * @returns {{place: object, km: number} | null}
 */
export function nearestPlaceInfo(lat, lng, maxKm = 200) {
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) return null;
  let best = null;
  let bestKm = Infinity;
  for (const p of PLACES) {
    // 緯度1度=111km、経度は緯度に応じて縮みます。順位付けに足ります。
    const dy = (p.lat - lat) * 111;
    const dx = (p.lng - lng) * 111 * Math.cos(lat * Math.PI / 180);
    const km = Math.hypot(dx, dy);
    if (km < bestKm) { bestKm = km; best = p; }
  }
  return best && bestKm <= maxKm
    ? { place: best, km: Math.round(bestKm) } : null;
}

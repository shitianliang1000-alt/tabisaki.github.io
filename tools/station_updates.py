def apply(stops, log=print):
    """[[lat, lng, name], ...] に差分をあてます。

    廃止駅は名前で消します。同じ名前の駅が別の路線にもある場合
    （「中里」など）に消しすぎないよう、消した件数を必ず出します。
    数が想定と違えば、そこで気づけるようにするためです。
    """
    removed_names = {n for names in REMOVED.values() for n in names}
    # 同名の別駅を巻き込みやすいものは、名前だけでは消しません。
    # 廃止路線はいずれも北海道・東北・山陰にあるので、その範囲に限ります。
    kept = []
    dropped = 0
    for lat, lng, name in stops:
        if name in removed_names and _in_closed_area(lat, lng):
            dropped += 1
            continue
        kept.append([lat, lng, name])

    renamed = 0
    for s in kept:
        if s[2] in RENAMED:
            s[2] = RENAMED[s[2]]
            renamed += 1

    have = {(round(s[0], 3), round(s[1], 3), s[2]) for s in kept}
    added = 0
    for lat, lng, name, _year, _note in ADDED:
        if (round(lat, 3), round(lng, 3), name) in have:
            continue
        kept.append([lat, lng, name])
        added += 1

    log(f"廃止 {dropped}件 / 改称 {renamed}件 / 追加 {added}件"
        f" → {len(stops)}駅 から {len(kept)}駅")
    return sorted(kept, key=lambda s: (s[0], s[1]))


def _in_closed_area(lat, lng):
    """廃止路線があった範囲（北海道・岩手・道南・山陰）か。"""
    if lat >= 41.2:                      # 北海道
        return True
    if 39.0 <= lat <= 40.5 and lng >= 140.8:   # 岩泉線まわり
        return True
    if 34.6 <= lat <= 35.3 and 132.0 <= lng <= 133.2:   # 三江線まわり
        return True
    return False

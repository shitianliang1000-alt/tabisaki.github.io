// 穴場として勧めてよいか、勧めるならどのくらいか。
//
// 「穴場」は、有名ではない場所の全部ではありません。行けば何かを
// 見たり、したりできて、それが説明から読み取れる場所です。県のページの
// 穴場の欄は、以前は有名さの点が無いものを名前の順に並べていたので、
//
//   長野県  X-JAM高井富士（スキー場）・ラーラ松本（温水プール）・
//           恵那山トンネル（中央道のトンネル）・奥秩父（山塊）
//   神奈川県 ひこしヶ谷横穴墓群・宮ノ前横穴墓群・姥川（準用河川）
//
// のように、あいうえお順の頭の方にある名前がそのまま出ていました。
//
// ここでは説明の書きぶりで点を付けます。
//
//   ・見どころを言う語（眺め・紅葉・天然記念物・散策・体験…）は加点
//   ・管理や分類だけを言う語（水系・準用河川・運営している・改名…）は減点
//   ・穴場の欄に向かない分類（スキー場・川・ダム・峠）は少し減点
//   ・広すぎるもの（山地・山脈・山塊）と、買い物の施設は欄に出さない
//
// 行き先かどうか（宿・トンネル・市民プール）は js/notaspot.js が決めます。
// ここは、行き先のうち「穴場として先に見せたいもの」の順番だけです。

/** 見どころ・すること を言う語。1語ごとに加点（同じ語は1回）。 */
const SIGHT_WORDS = [
  "眺め", "眺望", "展望", "見渡", "絶景", "景勝", "景観", "名勝", "天然記念物",
  "重要文化財", "国宝", "史跡に指定", "登録有形文化財", "百選", "遺産",
  "紅葉", "桜", "新緑", "雲海", "星空", "夕日", "朝日", "夜景", "花",
  "湧水", "清流", "透明", "奇岩", "洞窟", "鍾乳洞", "原生林", "巨木", "大木",
  "散策", "遊歩道", "ハイキング", "トレッキング", "登山道", "体験", "見学",
  "楽しめ", "味わえ", "名物", "伝統", "祭", "最古", "最大", "日本一", "唯一",
  "珍しい", "美しい", "知られ", "有名", "人気", "訪れ", "展示", "公開",
  "庭園", "町並み", "街並み", "古民家", "茅葺", "石垣", "滝", "渓谷",
];

/**
 * 管理・分類・沿革だけを言う語。読んでも、行って何があるかが分かりません。
 *
 *   姥川は、神奈川県相模原市を流れる相模川水系の準用河川。
 *   YAMABOKUワイルドスノーパークは、…2010年に山田牧場スキー場から改名された。
 *   鹿島槍スキー場は、…株式会社鹿島槍（日本駐車場開発の孫会社）が運営している。
 */
const ADMIN_WORDS = [
  "水系", "準用河川", "普通河川", "一級河川", "二級河川", "支流",
  "管理する", "管理している", "運営する", "運営している", "指定管理",
  "改名", "改称", "旧称", "株式会社", "子会社", "孫会社", "型式",
  "村社", "郷社", "産土神", "鎮守", "供用", "開業", "竣工", "道路橋",
];

/** 穴場の欄に並べると、続けて同じ種類に見えるもの。欄から外しはしません。 */
const WEAK_CATEGORY = new Map([
  ["スキー場", 2],   // 冬だけ。しかも大きな施設で、穴場という語に合いません
  ["川", 2],
  ["ダム", 1],
  ["峠", 2],
]);

/** 名前の終わりで分かる、小さな遺構の群。説明に見学の手がかりが無ければ減点。 */
//   上矢部町富士山古墳は、…にある古墳。形状は円墳。
const SMALL_REMAINS = /(横穴墓群|横穴群|古墳群?|窯跡|貝塚|遺跡)$/;
// 名前が「山代二子塚」でも、書き出しが「…にある古墳。」なら同じです。
const REMAINS_LEAD = /^[^。]{0,60}にある(古墳|横穴墓群?|古墳群)。/;
const VISITABLE = /公園|見学|公開|復元|展示|整備|資料館|散策/;

/**
 * 穴場の欄に出さないもの。
 *
 *   奥秩父山塊とは、東京、埼玉、山梨、長野の1都3県にまたがる山塊である。
 *     … 1都3県にまたがる山の連なりは、1日の行き先として1か所に置けません
 *   OSC湘南シティは、…複合商業施設・ショッピングセンター。
 *     … 買い物の施設は、どの町にもあるもので、穴場ではありません
 *   チャッキラコ・ふじさわ江の島花火大会
 *     … 催しは、その日に行かないと見られません
 */
const TOO_WIDE_NAME = /(山塊|山地|山脈|山系|丘陵|高地|水系|流域)$/;
// 「奥秩父」の書き出しは「奥秩父山塊とは」。名前が山・岳で終わるもの
// （和賀岳 … 書き出しは「和賀山塊は」）は、登れる1つの山なので残します。
const TOO_WIDE_LEAD = /^[^、。（(]{0,20}(山塊|山地|山脈)([（(][^）)]*[）)])?(とは|は)/;
// 催し。日が決まっていて、行けばいつでも見られるものではありません
// （チャッキラコは小正月、ふじさわ江の島花火大会は夏の1日）。
const EVENT_NAME = /(花火大会|まつり|祭り?|フェスティバル|フェス|七夕|鬼会)$/;
const EVENT_LEAD = /^[^。]{0,60}(伝統行事|行事|祭礼|花火大会|イベント)(である|。)/;
const SHOPPING = /複合商業施設|商業施設|ショッピングセンター|ショッピングモール|アウトレット/;

const PAREN = /[（(][^）)]*[）)]/g;
const baseName = (s) => String(s?.name ?? "").replace(PAREN, "").trim();

/**
 * エリア・都道府県のページの「観光地」「穴場」に並べないもの（旅程からは外しません）。
 *
 *   松本市美鈴湖もりの国オートキャンプ場 … 泊まって過ごす所で、立ち寄り先ではありません
 *   ヒカリヤ ニシ・旬彩 月の静香          … 1軒の店。説明も無く、見どころが読めません
 *
 * キャンプ場は js/notaspot.js では外しません（そこで過ごしたい人の旅程には要ります）。
 * ここで外すのは、ページで「観光地」として紹介する一覧からだけです。
 */
const CAMPSITE = /(キャンプ場|オートキャンプ|キャンプフィールド|キャンプ村|キャンプセンター|キャンプファーム|野営場)/;
// 料理の種類が名前の頭にある1軒の店（「旬彩 月の静香」「里山イタリアン AJIKURA」）。
const SHOP_LEAD = /^(旬彩|割烹|鮨|寿司|そば処|蕎麦処|里山イタリアン|イタリアン|フレンチ|ビストロ|ダイニング|カフェ|レストラン)(和食)?(\s|$)/;
// 名前だけでは店と分からないもの。外から指摘のあったものを、名指しで入れます。
const SHOP_NAMES = new Set(["ヒカリヤ ニシ", "ヒカリヤ ヒガシ"]);

/** ページの観光地の一覧に出してよいか。 */
export function fitsAreaList(spot) {
  const name = baseName(spot);
  if (!name) return false;
  if (CAMPSITE.test(name)) return false;
  if (SHOP_NAMES.has(name)) return false;
  if (SHOP_LEAD.test(name) && !spot?.description) return false;
  return true;
}

/** 穴場の欄に出してよいか。 */
export function fitsHiddenList(spot) {
  const name = baseName(spot);
  if (!name) return false;
  if (!fitsAreaList(spot)) return false;
  if (TOO_WIDE_NAME.test(name)) return false;
  const d = String(spot?.description ?? "");
  if (TOO_WIDE_LEAD.test(d) && !/(岳|山|峰)$/.test(name)) return false;
  if (SHOPPING.test(d)) return false;
  if (EVENT_NAME.test(name) || EVENT_LEAD.test(d)) return false;
  return true;
}

/**
 * 説明の具体さの点。大きいほど、穴場として先に見せます。
 *
 * @param {object} spot
 * @param {string} [text] ページに載せる説明（無ければ spot.description）
 */
export function gemScore(spot, text = spot?.description) {
  const d = String(text ?? "");
  let score = 0;
  for (const w of SIGHT_WORDS) if (d.includes(w)) score += 1;
  for (const w of ADMIN_WORDS) if (d.includes(w)) score -= 2;
  // 「幅70m」「樹齢800年」「約400 m」のような、見て分かる大きさ。
  if (/(幅|高さ|落差|樹齢|標高|全長|約)\s?[0-9０-９,.]+\s?(m|メートル|年|km|キロ)/.test(d)) score += 1;
  score -= WEAK_CATEGORY.get(spot?.category) ?? 0;
  if ((SMALL_REMAINS.test(baseName(spot)) || REMAINS_LEAD.test(d)) && !VISITABLE.test(d)) score -= 2;
  // 手で書いた説明（有名さの点が付いているもの）は、それだけで読めます。
  if (Number.isFinite(spot?.fame_score)) score += 3;
  return score;
}
